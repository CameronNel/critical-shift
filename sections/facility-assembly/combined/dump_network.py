"""Blender script: dump the hall network geometry to JSON for draw_network_plan.py.
    blender --background --python dump_network.py -- OUT.json
Uses the build script's LINKS and reactor_links.fillet, so the drawing is always the same geometry the build produces."""
import sys, json, os, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_combined_map as BM, reactor_links as R
out = sys.argv[sys.argv.index('--') + 1]
links = {}
paths = {k: R.Path(R.fillet(L['pts'], L['r'])) for k, L in BM.LINKS.items()}
for k, L in BM.LINKS.items():
    p = paths[k]; w = L.get('w', 5.0)
    air = []
    for a in L['airlocks']:
        sa = p.length - 2.4 if a is None else (p.length + a if a < 0 else a); q, d, _n = p.at(sa)
        air.append(dict(x=round(q.x, 2), y=round(q.y, 2), heading_deg=round(math.degrees(math.atan2(d.y, d.x)), 1), opening='2.4 x 2.87 m (spawn-room airlock copy), leaves parked open'))
    joins = []
    for t in ('into', 'outof'):
        if t in L:
            par, sg, pt = L[t]; q = paths[par].at(paths[par].nearest(pt))[0] if par in paths else None
            joins.append(dict(kind=t, parent=par, side='left' if sg == 1 else 'right', parent_point=[round(q.x, 2), round(q.y, 2)] if q else list(pt)))
    ends = [dict(at='start', xy=[round(p.at(0)[0].x, 2), round(p.at(0)[0].y, 2)]), dict(at='end', xy=[round(p.at(p.length)[0].x, 2), round(p.at(p.length)[0].y, 2)])]
    links[k] = dict(w=w, h=L.get('h', 5.0), zone=L.get('zone', k), line=[(round(q.x, 2), round(q.y, 2)) for q in p.P], len=round(p.length, 1),
                    into=L.get('into'), outof=L.get('outof'), requires=list(L.get('requires', (k,))), airlocks=air, junctions=joins, ends=ends, smoothing_radius=L['r'])
rooms = [dict(key=r[0], loc=r[3], rot=r[4]) for r in BM.ROOMS]
json.dump(dict(note='Generated by dump_network.py from build_combined_map.LINKS; plan metres, +x east, +y north, z up; all unreviewed. Hall interiors: floor z 0, clear height h, clear width w.', links=links, rooms=rooms), open(out, 'w'), indent=1)
print('DUMPED', len(links), 'links')
